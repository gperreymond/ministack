#!/bin/bash

# generated by ministack, run by 'ministack' (in a hashibase container) before starting the cluster
# - the ca is created once, and kept
# - the certificates are recreated every time, so they always match the nodes of the cluster

set -euo pipefail

cd /tls
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

if [ ! -f ca.pem ]; then
  echo "[INFO] creating the ministack ca..."
  (cd "$WORK" && consul tls ca create -days 3650 -common-name "ministack ca {{ name }}" > /dev/null)
  mv "$WORK"/consul-agent-ca.pem ca.pem
  mv "$WORK"/consul-agent-ca-key.pem ca-key.pem
fi

CA="-ca /tls/ca.pem -key /tls/ca-key.pem -days 3650"
echo "[INFO] creating the certificates..."
cd "$WORK"

# nomad: server.global.nomad / client.global.nomad, localhost and 127.0.0.1 are included by default
nomad tls cert create -server -region global $CA \
  {%- if services.nomad.servers %}
  {%- for item in services.nomad.servers %}
  -additional-dnsname '{{ datacenter }}-{{ item.name }}' -additional-ipaddress '{{ network_prefix }}.{{ 10 + loop.index }}' \
  {%- endfor %}
  {%- endif %}
  > /dev/null 2>&1
nomad tls cert create -client -region global $CA \
  {%- if services.nomad.clients %}
  {%- for item in services.nomad.clients %}
  {%- set loop_index = loop.index %}
  {%- if item.loop_index %}{%- set loop_index = item.loop_index %}{%- endif %}
  -additional-dnsname '{{ datacenter }}-{{ item.name }}' -additional-ipaddress '{{ network_prefix }}.{{ 100 + loop_index }}' \
  {%- endfor %}
  {%- endif %}
  > /dev/null 2>&1
mv global-server-nomad.pem /tls/nomad-server.pem
mv global-server-nomad-key.pem /tls/nomad-server-key.pem
mv global-client-nomad.pem /tls/nomad-client.pem
mv global-client-nomad-key.pem /tls/nomad-client-key.pem

# consul: server.{{ datacenter }}.consul / client.{{ datacenter }}.consul, localhost and 127.0.0.1 are included by default
consul tls cert create -server -dc '{{ datacenter }}' $CA \
  {%- if services.consul.servers %}
  {%- for item in services.consul.servers %}
  -additional-dnsname '{{ datacenter }}-{{ item.name }}' -additional-ipaddress '{{ network_prefix }}.{{ 20 + loop.index }}' \
  {%- endfor %}
  {%- endif %}
  > /dev/null
consul tls cert create -client -dc '{{ datacenter }}' $CA > /dev/null
mv '{{ datacenter }}-server-consul-0.pem' /tls/consul-server.pem
mv '{{ datacenter }}-server-consul-0-key.pem' /tls/consul-server-key.pem
mv '{{ datacenter }}-client-consul-0.pem' /tls/consul-client.pem
mv '{{ datacenter }}-client-consul-0-key.pem' /tls/consul-client-key.pem

# vault
consul tls cert create -server -dc '{{ datacenter }}' $CA \
  -additional-dnsname '{{ datacenter }}-vault' -additional-ipaddress '{{ network_prefix }}.30' > /dev/null
mv '{{ datacenter }}-server-consul-0.pem' /tls/vault.pem
mv '{{ datacenter }}-server-consul-0-key.pem' /tls/vault-key.pem

# local stack: readable by every container user (vault runs as 'vault')
chmod 644 /tls/*.pem
echo "[INFO] certificates are in .ministack/tls"
{%- endif %}
